// Isolated synthetic scanner/state fixture on 3001 and Vite on 5179 only.
async page => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.context().addInitScript(() => localStorage.setItem('stock5-0-password', 'test-only-password'));
  await page.goto('http://127.0.0.1:5179/stock5-0/tests/chart-controls.browser.html');
  const menu = page.getByLabel('차트 그룹 선택');
  await menu.waitFor();
  const options = await menu.locator('option').allTextContents();
  check(options.includes('8. 구름돌파') && options.includes('9. 종목들') && !options.includes('8. 종목들'), 'menu numbering');
  await menu.selectOption('cloud');
  await page.waitForFunction(() => document.querySelector('.scan-progress')?.textContent.includes('전체 검색 완료'), null, { timeout: 45000 });
  const rows = page.locator('.scan-table tbody tr');
  check(await rows.count() > 0, 'daily cloud matches');
  const colours = await rows.locator('td:nth-child(6) small').allTextContents();
  check(colours.includes('양운') && colours.includes('음운'), 'both cloud colours appear');
  check(await rows.first().locator('td').nth(3).textContent() === '2026-10-08', 'actual latest comparison date');
  check((await rows.first().locator('.position-mini-controls button').allTextContents()).join('|') === '롱 보유|롱 관심|숏 관심|숏 보유|준비!|주의!', 'same shared controls as menu6/7');
  const direction = page.getByLabel('구름 돌파 하락 필터');
  await direction.selectOption('breakout');
  check(await rows.count() > 0 && (await rows.locator('td:nth-child(3)').allTextContents()).every(text => text === '돌파'), 'up filter');
  await direction.selectOption('breakdown');
  check(await rows.count() > 0 && (await rows.locator('td:nth-child(3)').allTextContents()).every(text => text === '하락'), 'down filter');
  await direction.selectOption('all');
  await page.getByLabel('검색 시장 필터').selectOption('japan');
  check(await rows.count() > 0 && (await rows.locator('td:nth-child(2)').allTextContents()).every(text => text.includes('일본')), 'market filter');
  await page.getByLabel('검색 결과 종목명 또는 코드').fill('__no_match__');
  check(await rows.count() === 0, 'search combines with market filter');
  await page.getByLabel('검색 결과 종목명 또는 코드').fill('');
  await page.getByLabel('검색 시장 필터').selectOption('all');
  const maSymbols = await rows.locator('.scan-stock-cell small').allTextContents();
  await page.getByLabel('구름돌파 검색 기준').selectOption('candle');
  await rows.first().waitFor({ timeout: 45000 });
  check((await page.locator('.scan-table th').allTextContents()).includes('최근 종가'), 'candle headers use close, not SMA20');
  const candleSymbols = await rows.locator('.scan-stock-cell small').allTextContents();
  check(candleSymbols.some(symbol => !maSymbols.includes(symbol)), 'candle mode is independently calculated, not relabeled SMA results');
  await direction.selectOption('breakout');
  check(await rows.count() > 0 && (await rows.locator('td:nth-child(3)').allTextContents()).every(text => text === '돌파'), 'candle up filter');
  await direction.selectOption('breakdown');
  check(await rows.count() > 0 && (await rows.locator('td:nth-child(3)').allTextContents()).every(text => text === '하락'), 'candle down filter');
  await direction.selectOption('all');
  await page.locator('.scan-timeframes').getByRole('button', { name: '주', exact: true }).click();
  await rows.first().waitFor({ timeout: 45000 });
  check((await page.locator('.scan-table th').allTextContents()).includes('최근 종가'), 'weekly candles supported');
  await page.getByLabel('구름돌파 검색 기준').selectOption('ma20');
  await rows.first().waitFor({ timeout: 45000 });
  check((await page.locator('.scan-table th').allTextContents()).includes('최근 20이평'), 'weekly SMA20 supported');
  check((await page.locator('.scan-description').allTextContents()).some(text => text.includes('현재 진행 중인 이번 주봉')), 'partial week explained');
  const count = await rows.count();
  check(count > 0, 'weekly cloud matches');
  const symbol = await rows.first().locator('.scan-stock-cell small').textContent();
  await rows.first().locator('.scan-stock-link').click();
  const dialog = page.locator('.scan-chart-dialog[open]');
  await dialog.locator('.position-mini-controls').waitFor();
  check(await dialog.locator('.chart-section').count() === 4, 'same four-chart popup');
  const timeframes = await dialog.locator('.tf-btn.active').allTextContents();
  check(timeframes.length === 2 && timeframes.every(text => text === '주'), 'weekly popup timeframes');
  const watch = dialog.getByRole('button', { name: '롱 관심', exact: true });
  if (await watch.getAttribute('aria-pressed') !== 'true') await watch.click();
  await page.waitForFunction(() => document.querySelector('.scan-chart-dialog .position-mini-controls')?.getAttribute('aria-busy') === 'false');
  await dialog.getByRole('button', { name: '차트 팝업 닫기' }).click();
  await menu.selectOption('saved-stocks');
  await page.getByLabel('저장 종목명 또는 코드').fill(symbol);
  check(await page.locator('.saved-stock-table tbody tr').count() === 1, 'menu8 records appear in menu9');
  await page.getByLabel('저장 종목명 또는 코드').fill('');
  await page.setViewportSize({ width: 390, height: 844 });
  await menu.selectOption('cloud');
  await rows.first().waitFor({ timeout: 45000 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile scroll stays inside table');
  await page.setViewportSize({ width: 1600, height: 1000 });
  return { menuNumbering: true, candleAndMA20: true, dailyAndWeekly: true, bothCloudColours: true, upDownMarketSearchFilters: true, weeklyResults: count, sharedRecords: true, fourCharts: true, mobileInternalScroll: true };
}
